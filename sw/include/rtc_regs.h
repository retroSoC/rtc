#ifndef RTC_REGS_H
#define RTC_REGS_H

#include <stdint.h>

/* Keep these hand-written definitions aligned with rtl/rtc_define.svh. */
#define RTC_CTRL_OFFSET                UINT32_C(0x000)
#define RTC_STATUS_OFFSET              UINT32_C(0x004)
#define RTC_COMMAND_OFFSET             UINT32_C(0x008)
#define RTC_COMMAND_STATUS_OFFSET      UINT32_C(0x00C)
#define RTC_TIME_LOAD_LO_OFFSET        UINT32_C(0x010)
#define RTC_TIME_LOAD_HI_OFFSET        UINT32_C(0x014)
#define RTC_TIME_LOAD_SUBSEC_OFFSET    UINT32_C(0x018)
#define RTC_SNAPSHOT_TIME_LO_OFFSET    UINT32_C(0x01C)
#define RTC_SNAPSHOT_TIME_HI_OFFSET    UINT32_C(0x020)
#define RTC_SNAPSHOT_SUBSEC_OFFSET     UINT32_C(0x024)
#define RTC_SECOND_CYCLES_OFFSET       UINT32_C(0x028)
#define RTC_CALIB_PPM_OFFSET           UINT32_C(0x02C)
#define RTC_ALARM0_TIME_LO_OFFSET      UINT32_C(0x030)
#define RTC_ALARM0_TIME_HI_OFFSET      UINT32_C(0x034)
#define RTC_ALARM0_SUBSEC_OFFSET       UINT32_C(0x038)
#define RTC_ALARM1_TIME_LO_OFFSET      UINT32_C(0x03C)
#define RTC_ALARM1_TIME_HI_OFFSET      UINT32_C(0x040)
#define RTC_ALARM1_SUBSEC_OFFSET       UINT32_C(0x044)
#define RTC_ALARM_ENABLE_OFFSET        UINT32_C(0x048)
#define RTC_PERIOD_RELOAD_OFFSET       UINT32_C(0x04C)
#define RTC_PERIOD_CTRL_OFFSET         UINT32_C(0x050)
#define RTC_EVENT_RAW_OFFSET           UINT32_C(0x054)
#define RTC_EVENT_CLEAR_OFFSET         UINT32_C(0x058)
#define RTC_EVENT_TEST_OFFSET          UINT32_C(0x05C)
#define RTC_INTR_ENABLE_OFFSET         UINT32_C(0x060)
#define RTC_INTR_STATE_OFFSET          UINT32_C(0x064)
#define RTC_WAKE_ENABLE_OFFSET         UINT32_C(0x068)
#define RTC_WAKE_STATE_OFFSET          UINT32_C(0x06C)
#define RTC_CLOCK_HZ_OFFSET            UINT32_C(0x0F0)
#define RTC_IP_ID_OFFSET               UINT32_C(0x0F4)
#define RTC_IP_VERSION_OFFSET          UINT32_C(0x0F8)
#define RTC_CAPABILITY_OFFSET          UINT32_C(0x0FC)

#define RTC_CTRL_ENABLE_MASK           UINT32_C(0x00000001)
#define RTC_STATUS_ENABLED_MASK        (UINT32_C(1) << 0U)
#define RTC_STATUS_TIME_VALID_MASK     (UINT32_C(1) << 1U)
#define RTC_STATUS_COMMAND_BUSY_MASK   (UINT32_C(1) << 2U)
#define RTC_STATUS_COMMAND_DONE_MASK   (UINT32_C(1) << 3U)
#define RTC_STATUS_COMMAND_ERROR_MASK  (UINT32_C(1) << 4U)
#define RTC_STATUS_SNAPSHOT_VALID_MASK (UINT32_C(1) << 5U)
#define RTC_STATUS_LINK_READY_MASK     (UINT32_C(1) << 6U)
#define RTC_COMMAND_STATUS_DONE_MASK   (UINT32_C(1) << 1U)
#define RTC_COMMAND_STATUS_ERROR_MASK  (UINT32_C(1) << 2U)

#define RTC_COMMAND_APPLY_CONFIG       UINT32_C(1)
#define RTC_COMMAND_SET_TIME           UINT32_C(2)
#define RTC_COMMAND_SNAPSHOT           UINT32_C(3)
#define RTC_COMMAND_CLEAR_EVENTS       UINT32_C(4)
#define RTC_COMMAND_INJECT_EVENTS      UINT32_C(5)

#define RTC_PERIOD_ENABLE_MASK         UINT32_C(0x00000001)
#define RTC_PERIOD_AUTO_RELOAD_MASK    UINT32_C(0x00000002)

#define RTC_EVENT_SECOND_MASK          UINT32_C(0x00000001)
#define RTC_EVENT_ALARM0_MASK          UINT32_C(0x00000002)
#define RTC_EVENT_ALARM1_MASK          UINT32_C(0x00000004)
#define RTC_EVENT_PERIODIC_MASK        UINT32_C(0x00000008)
#define RTC_EVENT_OVERFLOW_MASK        UINT32_C(0x00000010)
#define RTC_EVENT_VALID_MASK           UINT32_C(0x0000001F)

#define RTC_SUBSECOND_HZ               UINT32_C(256)
#define RTC_SECOND_CYCLES_MIN          UINT32_C(256)
#define RTC_CALIB_PPM_MIN              (-488)
#define RTC_CALIB_PPM_MAX              488
#define RTC_IP_ID_VALUE                UINT32_C(0x52544332)
#define RTC_ABI_VERSION                UINT32_C(2)

#endif
